// Модель контента посадочной страницы.
//
// Страницы первой волны (см. seo/pagemap.tsv) не пишутся руками по одной: у них общая
// структура — заголовок под запрос-ядро, короткий ввод, разбор по блокам, FAQ под
// хвостовые запросы и один простой призыв к действию. Здесь описан контракт, в
// src/content/seo/* лежит сам текст, а рисует всё <SeoPage>.

export interface SeoSection {
  title: string;
  /** Абзац текста. Может быть пустым, если блок держится на списке. */
  body?: string;
  bullets?: string[];
  /** Моноширинный блок: команда, код ответа, фрагмент конфига. */
  code?: string;
  /** Сравнительная таблица: шапка и строки. Последняя колонка подсвечивается как наша. */
  table?: { head: string[]; rows: string[][] };
  /** Сноска под блоком — мелким шрифтом: оговорки и «проверьте актуальность». */
  note?: string;
}

export interface SeoFaq {
  q: string;
  a: string;
}

export interface SeoPageContent {
  /** Адрес страницы — он же ключ в реестре. */
  url: string;
  /** <title>. До 60 знаков, с ядром запроса в начале. */
  title: string;
  /** meta description. 140–170 знаков, с пользой и глаголом. */
  description: string;
  h1: string;
  /** Первый абзац: отвечает на запрос сразу, без разгона. */
  lead: string;
  /** Запросы, под которые страница прошита. В разметку не идут — это опора для текста. */
  keywords: string[];
  sections: SeoSection[];
  faq: SeoFaq[];
  /** Ссылки на соседние страницы: перелинковка и следующий шаг для читателя. */
  related: string[];
  cta: {
    title: string;
    text: string;
    /** Подпись под кнопкой: снимает страх «сейчас попросят карту». */
    note?: string;
    /** Кнопка ведёт сюда; по умолчанию — регистрация. */
    href?: string;
    label?: string;
  };
  /** Хлебные крошки: раздел, в который входит страница. */
  breadcrumb?: { title: string; href: string };
}
